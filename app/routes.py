#!/usr/bin/env python3
"""Writes both apps' list of screens from app/routes.json, as app/strings/generate.py writes their words.

  python3 app/routes.py           write the generated files
  python3 app/routes.py --check   fail if a generated file differs from what this writes

app/routes.json names every screen both apps can open by name: its route (`taf/{taf}/setup/versions`),
the line key of its title in app/strings, and, when not everyone may open it, what the person needs:
`manages` for someone who manages that taf, or an account capability (`cards.manage`, `billing.manage`,
`members.manage`, `account.delete`). Each app opens every route through one function, and a unit test
in each app fails on a route it has no case for.

Generated here: ios/Tafs/Design/AppRoutes.swift and
android/app/src/main/kotlin/bot/tafs/app/model/AppRoutes.kt. Nobody edits a generated file by hand.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
ROUTES = os.path.join(HERE, "routes.json")
STRINGS = os.path.join(HERE, "strings")
IOS_SWIFT = os.path.join(REPO, "ios", "Tafs", "Design", "AppRoutes.swift")
ANDROID_KT = os.path.join(REPO, "android", "app", "src", "main", "kotlin", "bot", "tafs", "app", "model", "AppRoutes.kt")

# What a route may need. `manages`: the person manages the taf the route names. The others are KIFF's
# account capabilities, as both apps read them.
NEEDS = ("manages", "cards.manage", "billing.manage", "members.manage", "account.delete")
SEGMENT = re.compile(r"^([a-z][a-z0-9]*(-[a-z0-9]+)*|\{[a-z][a-z0-9_]*\})$")
PLACEHOLDER = re.compile(r"\{([a-z][a-z0-9_]*)(\|possessive)?\}")
HEADER = "Generated by app/routes.py from app/routes.json: edit those, then run `python3 app/routes.py`."


def load(path=ROUTES):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    if set(data) != {"routes"} or not isinstance(data["routes"], list):
        raise ValueError("routes.json holds one field, `routes`, a list")
    return data["routes"]


def english(folder=STRINGS):
    """The English lines by key, from app/strings/en/: a route's title must be one of them."""
    sys.path.insert(0, folder)
    try:
        import generate
        return generate.load("en", folder)
    finally:
        sys.path.remove(folder)


def params(route):
    """The values a route takes, in order: `taf/{taf}/card` takes `taf`."""
    return [s[1:-1] for s in route.split("/") if s.startswith("{")]


def name(route):
    """A route's case name in both apps, from its fixed parts: `taf/{taf}/setup/versions` is `TafSetupVersions`."""
    parts = [s for s in route.split("/") if not s.startswith("{")]
    return "".join(w.capitalize() for p in parts for w in p.split("-"))


def problems(routes, lines):
    """Everything wrong with the list, as plain lines; empty when it's right."""
    out, seen, names, shapes = [], set(), {}, {}
    for i, entry in enumerate(routes):
        where = f"routes[{i}]"
        if not isinstance(entry, dict):
            out.append(f"{where}: not an object")
            continue
        extra = set(entry) - {"route", "title", "needs"}
        if extra:
            out.append(f"{where}: unknown fields {sorted(extra)}")
        route, title, needs = entry.get("route"), entry.get("title"), entry.get("needs")
        if not isinstance(route, str) or not route:
            out.append(f"{where}: no route")
            continue
        where = route
        segments = route.split("/")
        if not all(SEGMENT.match(s) for s in segments):
            out.append(f"{where}: each part is lowercase words joined by '-', or a `{{value}}`")
        if segments[0].startswith("{"):
            out.append(f"{where}: starts with a fixed part")
        if len(set(params(route))) != len(params(route)):
            out.append(f"{where}: a value named twice")
        if route in seen:
            out.append(f"{where}: listed twice")
        seen.add(route)
        shape = "/".join("{}" if s.startswith("{") else s for s in segments)
        if shape in shapes and shapes[shape] != route:
            out.append(f"{where}: the same path as {shapes[shape]}, so a path can't tell them apart")
        shapes.setdefault(shape, route)
        n = name(route)
        if n in names and names[n] != route:
            out.append(f"{where}: its case name {n} is {names[n]}'s too")
        names.setdefault(n, route)
        if not isinstance(title, str) or title not in lines:
            out.append(f"{where}: title {title!r} isn't a line in app/strings/en")
        elif isinstance(lines[title], str):
            missing = {m.group(1) for m in PLACEHOLDER.finditer(lines[title])} - set(params(route))
            # A title's value is filled by the app from the route's value (the taf's name for `{taf}`).
            if missing:
                out.append(f"{where}: its title needs {sorted(missing)}, which the route doesn't name")
        else:
            out.append(f"{where}: title {title} is a count's line, not a title")
        if needs is not None and needs not in NEEDS:
            out.append(f"{where}: needs {needs!r}, not one of {', '.join(NEEDS)}")
        if needs == "manages" and "taf" not in params(route):
            out.append(f"{where}: needs `manages` but names no taf")
    return out


def lower(n):
    return n[0].lower() + n[1:]


def swift(routes):
    out = [f"// {HEADER}", "", "import Foundation", "",
           "/// Every screen both apps open by name (app/routes.json). `AppModel.open(_:)` handles each one,",
           "/// and a unit test fails on a route it has no case for.",
           "enum AppRoute: String, CaseIterable, Sendable {"]
    for r in routes:
        out.append(f'    case {lower(name(r["route"]))} = "{r["route"]}"')
    out += ["", "    /// The key of the screen's title in app/strings.", "    var titleKey: String {", "        switch self {"]
    for r in routes:
        out.append(f'        case .{lower(name(r["route"]))}: return "{r["title"]}"')
    out += ["        }", "    }", "",
            "    /// What the person needs to open it: nil for anyone, `manages` for someone who manages the taf",
            "    /// it names, or else an account capability.",
            "    var needs: String? {", "        switch self {"]
    for r in routes:
        needs = r.get("needs")
        out.append(f'        case .{lower(name(r["route"]))}: return {json.dumps(needs) if needs else "nil"}')
    out += ["        }", "    }", "",
            "    /// The values this route takes, in order.",
            "    var parameters: [String] {",
            "        rawValue.split(separator: \"/\").filter { $0.hasPrefix(\"{\") }.map { String($0.dropFirst().dropLast()) }",
            "    }", "",
            "    /// The route a path names, and its values: `taf/3f2a/setup/versions` is `.tafSetupVersions`,",
            "    /// [\"taf\": \"3f2a\"]. Nil when no route matches.",
            "    static func match(_ path: String) -> (route: AppRoute, values: [String: String])? {",
            "        let parts = path.split(separator: \"/\", omittingEmptySubsequences: false).map(String.init)",
            "        for route in allCases {",
            "            let pattern = route.rawValue.split(separator: \"/\").map(String.init)",
            "            guard pattern.count == parts.count else { continue }",
            "            var values: [String: String] = [:]",
            "            var matches = true",
            "            for (want, got) in zip(pattern, parts) {",
            "                if want.hasPrefix(\"{\") {",
            "                    if got.isEmpty { matches = false; break }",
            "                    values[String(want.dropFirst().dropLast())] = got",
            "                } else if want != got {",
            "                    matches = false",
            "                    break",
            "                }",
            "            }",
            "            if matches { return (route, values) }",
            "        }",
            "        return nil",
            "    }",
            "}", ""]
    return "\n".join(out)


def kotlin(routes):
    out = [f"// {HEADER}", "", "package bot.tafs.app.model", "",
           "/** Every screen both apps open by name (app/routes.json). `AppModel.open(route)` handles each one,",
           " * and a unit test fails on a route it has no case for. `needs`: null for anyone, `manages` for",
           " * someone who manages the taf it names, or else an account capability. */",
           "enum class AppRoute(val pattern: String, val titleKey: String, val needs: String?) {"]
    for i, r in enumerate(routes):
        needs = json.dumps(r["needs"]) if r.get("needs") else "null"
        end = ";" if i == len(routes) - 1 else ","
        out.append(f'  {name(r["route"])}("{r["route"]}", "{r["title"]}", {needs}){end}')
    out += ["",
            "  /** The values this route takes, in order. */",
            "  val parameters: List<String> get() = pattern.split(\"/\").filter { it.startsWith(\"{\") }.map { it.drop(1).dropLast(1) }",
            "",
            "  companion object {",
            "    /** The route a path names, and its values: `taf/3f2a/setup/versions` is [TafSetupVersions],",
            "     * {taf=3f2a}. Null when no route matches. */",
            "    fun match(path: String): Pair<AppRoute, Map<String, String>>? {",
            "      val parts = path.split(\"/\")",
            "      for (route in entries) {",
            "        val pattern = route.pattern.split(\"/\")",
            "        if (pattern.size != parts.size) continue",
            "        val values = mutableMapOf<String, String>()",
            "        var matches = true",
            "        for ((want, got) in pattern.zip(parts)) {",
            "          if (want.startsWith(\"{\")) {",
            "            if (got.isEmpty()) { matches = false; break }",
            "            values[want.drop(1).dropLast(1)] = got",
            "          } else if (want != got) {",
            "            matches = false",
            "            break",
            "          }",
            "        }",
            "        if (matches) return route to values",
            "      }",
            "      return null",
            "    }",
            "  }",
            "}", ""]
    return "\n".join(out)


def generated(routes):
    return {IOS_SWIFT: swift(routes), ANDROID_KT: kotlin(routes)}


def main(argv):
    check = "--check" in argv
    routes = load()
    wrong = problems(routes, english())
    if wrong:
        print("\n".join(f"app/routes.json: {w}" for w in wrong), file=sys.stderr)
        return 1
    stale = []
    for path, text in generated(routes).items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == text:
            continue
        if check:
            stale.append(os.path.relpath(path, REPO))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if stale:
        print("Not what app/routes.py writes; run `python3 app/routes.py`: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
