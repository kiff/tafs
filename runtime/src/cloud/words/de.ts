import type { When, Words } from "./en.js";

/** "at" a time, as the language says it with and without a weekday (docs/languages.md). */
const at = (t: When) => (t.day ? `am ${t.day} um ${t.hm}` : `um ${t.hm}`);
/** A list joined as the language joins one ("A, B und C"), and a line's first letter capitalized. */
const list = (xs: string[]) => new Intl.ListFormat("de", { type: "conjunction" }).format(xs);
const cap = (x: string) => x.charAt(0).toUpperCase() + x.slice(1);
/** A weekday's name by number (Sunday 0), and a day code ("mon") by number. */
const day = (d: number, style: "long" | "short") => new Intl.DateTimeFormat("de", { weekday: style, timeZone: "UTC" }).format(new Date(Date.UTC(2023, 0, 1 + d)));
const code = (c: string) => Math.max(0, ["sun", "mon", "tue", "wed", "thu", "fri", "sat"].indexOf(c));

