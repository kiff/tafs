/** A time as a line says it ("금 14:20"), and "at" a time, as the language says it with and without a weekday (docs/languages.md). */
const bare = (t: When) => (t.day ? `${t.day} ${t.hm}` : t.hm);
const at = (t: When) => `${bare(t)}에`;
/** A list joined as the language joins one ("A, B 및 C"). */
const list = (xs: string[]) => new Intl.ListFormat("ko", { type: "conjunction" }).format(xs);
/** A weekday's name by number (Sunday 0), and a day code ("mon") by number. */
const day = (d: number, style: "long" | "short") => new Intl.DateTimeFormat("ko", { weekday: style, timeZone: "UTC" }).format(new Date(Date.UTC(2023, 0, 1 + d)));
const code = (c: string) => Math.max(0, ["sun", "mon", "tue", "wed", "thu", "fri", "sat"].indexOf(c));

