#!/usr/bin/env bash
# Writes src/coach-skills.ts from skills/<name>/<version>/SKILL.md (kiff/tafs#218):
# the skills tafs cloud stores for each account on kiff/agents before a
# definition names them. The files are the source; the test fails when the
# module is out of date. Usage: scripts/coach-skills.sh
set -euo pipefail
cd "$(dirname "$0")/.."
node -e '
const fs = require("fs");
const path = require("path");
const out = [];
for (const name of fs.readdirSync("skills").sort()) {
  const dir = path.join("skills", name);
  for (const version of fs.readdirSync(dir).sort()) {
    const md = path.join(dir, version, "SKILL.md");
    if (fs.statSync(path.join(dir, version)).isDirectory() && fs.existsSync(md)) {
      out.push({ name, version, skill_md: fs.readFileSync(md, "utf8") });
    }
  }
}
fs.writeFileSync("src/coach-skills.ts", `// Generated by scripts/coach-skills.sh from skills/<name>/<version>/SKILL.md. Do not edit by hand: run the script.
/** The skills tafs cloud stores for each account, by name and version (kiff/tafs#218). A stored version never changes. */
export const SKILLS: readonly { name: string; version: string; skill_md: string }[] = ${JSON.stringify(out, null, 2)};
`);
console.log(`wrote ${out.length} skills`);
'
