#!/usr/bin/env node
// Reads skills/coach/<name>/<version>/SKILL.md (Coach's skills, in the Agent Skills format: a front
// matter with name and description, then the body) into src/coach-skills.ts, which tafs cloud
// serves to kiff/agents and loads per conversation (runtime/src/cloud/coach-skills.ts). Run after
// changing a skill:
//   node scripts/coach-skills.mjs
// A stored version never changes in kiff/agents: a changed body under the same version is refused
// there, so a change bumps the version directory. The test (test/coach-skills.test.ts) fails when
// the generated module no longer matches the files.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** skills/coach/lock.json: each stored version's digest. A version kiff/agents holds never changes. */
export const LOCK = "lock.json";

export function digestOf(skillMD) {
  return createHash("sha256").update(skillMD).digest("hex");
}

/**
 * Checks each skill against the lock: a version in the lock with another digest is refused (bump the
 * version directory instead), a new version is added. Answers the lock to write.
 */
export function checkLock(skills, lock) {
  const next = { ...lock };
  for (const s of skills) {
    const key = `${s.name}@${s.version}`;
    const d = digestOf(s.skill_md);
    if (lock[key] && lock[key] !== d) throw new Error(`${key}: its text changed, but a stored version never changes in kiff/agents: move it to a new version directory`);
    next[key] = d;
  }
  return next;
}

const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const VERSION = /^[A-Za-z0-9.-]{1,64}$/;

/** Parses one SKILL.md: the front matter's name and description, and the body. */
export function parseSkill(text, file) {
  const fail = (why) => { throw new Error(`${file}: ${why}`); };
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text.replace(/\r\n/g, "\n"));
  if (!m) fail("a SKILL.md starts with a front matter between --- lines");
  const front = {};
  for (const raw of m[1].split("\n")) {
    const l = /^([a-z]+):\s*(.*)$/.exec(raw.trim());
    if (!l) fail(`front matter line not understood: ${raw}`);
    front[l[1]] = l[2].trim();
  }
  if (!NAME.test(front.name ?? "")) fail("name is lower-case words joined by hyphens");
  if (!front.description || front.description.length > 1024) fail("description is one sentence of at most 1,024 characters");
  const body = m[2].trim();
  if (!body) fail("the body is missing");
  return { name: front.name, description: front.description, body };
}

export function readSkills(root) {
  const out = [];
  for (const name of readdirSync(root).sort()) {
    const dir = join(root, name);
    if (!statSync(dir).isDirectory()) continue;
    const versions = readdirSync(dir).filter((v) => statSync(join(dir, v)).isDirectory()).sort();
    if (versions.length !== 1) throw new Error(`${dir}: one version directory, the one in use`);
    const version = versions[0];
    if (!VERSION.test(version)) throw new Error(`${dir}/${version}: a version is letters, digits, dots and hyphens`);
    const file = join(dir, version, "SKILL.md");
    const skill = parseSkill(readFileSync(file, "utf8"), file);
    if (skill.name !== name) throw new Error(`${file}: names ${skill.name}, not its directory ${name}`);
    out.push({ ...skill, version, skill_md: readFileSync(file, "utf8").replace(/\r\n/g, "\n") });
  }
  return out;
}

export function render(skills) {
  return `// Generated by scripts/coach-skills.mjs from skills/coach/*/*/SKILL.md. Do not edit by hand: run the script.
/** Coach's skills: each a stored version in kiff/agents, loaded per conversation by tafs cloud (cloud/coach-skills.ts). */
export const COACH_SKILLS = ${JSON.stringify(skills.map(({ name, version, description, body, skill_md }) => ({ name, version, description, body, skill_md })), null, 2)} as const;
`;
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(here, "..", "skills", "coach");
  const skills = readSkills(root);
  const lockFile = join(root, LOCK);
  const lock = checkLock(skills, existsSync(lockFile) ? JSON.parse(readFileSync(lockFile, "utf8")) : {});
  writeFileSync(lockFile, JSON.stringify(lock, null, 2) + "\n");
  writeFileSync(join(here, "..", "src", "coach-skills.ts"), render(skills));
  console.log(`${skills.length} skills: ${skills.map((s) => `${s.name}@${s.version} (${s.body.length} chars)`).join(", ")}`);
}
