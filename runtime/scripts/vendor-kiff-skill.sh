#!/usr/bin/env bash
# Pins KIFF's own `kiff` skill (kiff/kiff-plugins) for the job agents.
# Writes skills/kiff/SKILL.md, for people to read, and src/kiff-skill.ts, which
# setup uploads. Usage: scripts/vendor-kiff-skill.sh [commit]  (default: latest on main)
set -euo pipefail
cd "$(dirname "$0")/.."
REPO=kiff/kiff-plugins
SRC=plugins/kiff-cards/skills/kiff/SKILL.md
COMMIT=${1:-$(gh api "repos/$REPO/commits?path=$SRC&per_page=1" --jq '.[0].sha')}
gh api "repos/$REPO/contents/$SRC?ref=$COMMIT" --jq .content | base64 -d > skills/kiff/SKILL.md
node -e '
const fs = require("fs");
const [repo, path, commit] = process.argv.slice(1);
const content = fs.readFileSync("skills/kiff/SKILL.md", "utf8");
fs.writeFileSync("src/kiff-skill.ts", `// Generated by scripts/vendor-kiff-skill.sh. Do not edit by hand: run the script.
/** KIFF\x27s own \`kiff\` skill, pinned to one commit of ${repo}. */
export const KIFF_SKILL = {
  repo: ${JSON.stringify(repo)},
  path: ${JSON.stringify(path)},
  commit: ${JSON.stringify(commit)},
  content: ${JSON.stringify(content)},
} as const;
`);
' "$REPO" "$SRC" "$COMMIT"
echo "pinned $REPO@$COMMIT"
